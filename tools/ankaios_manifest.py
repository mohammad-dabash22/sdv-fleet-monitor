"""Write the Ankaios manifest (deploy/ankaios/state.yaml) from config/fleet.json.

Every van gets the same workloads, only its settings differ, so the manifest is
generated instead of written by hand. To add a van, add one line to
config/fleet.json and run:

    python -m tools.ankaios_manifest

Each van has its own Ankaios agent, named after its vehicle_id (like one agent
per vehicle ECU). Per van: Kuksa Databroker + simulator + hazard_detector.

NEXT PHASE: add the cloud_publisher workload once Zenoh is real (the fake Zenoh
only works inside one process, so a publisher in its own container cannot reach
the cloud).
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
FLEET = ROOT / "config" / "fleet.json"
OUT = ROOT / "deploy" / "ankaios" / "state.yaml"

HEADER = """\
# GENERATED by `python -m tools.ankaios_manifest` from config/fleet.json. Do not edit by hand.
#
# Build the images once (from the repository root):
#   podman build -f deploy/docker/databroker.Dockerfile -t localhost/sdv-fleet/databroker:dev .
#   podman build -f deploy/docker/vehicle.Dockerfile    -t localhost/sdv-fleet/vehicle:dev .
#
# Run (each command in its own terminal; one agent per van):
#   ank-server --insecure --startup-manifest deploy/ankaios/state.yaml
#   ank-agent  --insecure --name veh-01 --server-url http://127.0.0.1:25551
#   ank -k get workloads
#
# All containers use the host network, so the apps reach their van's Databroker
# on 127.0.0.1 at the port from config/fleet.json.

apiVersion: v1
workloads:
"""


def _flow(items: list[str]) -> str:
    """A YAML flow list, e.g. ["--net=host", "-e", "A=1"] (JSON strings are valid YAML)."""
    return "[" + ", ".join(json.dumps(i) for i in items) + "]"


def _workload(name: str, agent: str, image: str, options: list[str], args: list[str],
              depends_on: str | None = None) -> str:
    lines = [
        f"  {name}:",
        "    runtime: podman",
        f"    agent: {agent}",
        "    restartPolicy: ALWAYS",
    ]
    if depends_on:
        lines += ["    dependencies:", f"      {depends_on}: ADD_COND_RUNNING"]
    lines += [
        "    runtimeConfig: |",
        f"      image: {image}",
        f"      commandOptions: {_flow(options)}",
        f"      commandArgs: {_flow(args)}",
    ]
    return "\n".join(lines) + "\n"


def render(fleet: dict, images: str = "localhost/sdv-fleet") -> str:
    out = [HEADER]
    for v in fleet["vehicles"]:
        vid, route = v["vehicle_id"], v["route_id"]
        port = str(v["databroker_port"])
        env = {
            "VEHICLE_ID": vid,
            "ROUTE_ID": route,
            "SPEED_LIMIT_KMH": fleet["routes"][route]["speed_limit_kmh"],
            "DATABROKER_PORT": port,
        }
        app_options = ["--net=host"]
        for key, value in env.items():
            app_options += ["-e", f"{key}={value}"]
        broker = f"{vid}-databroker"

        out.append(f"\n  # {'-' * 60} {v.get('name', vid)}, Route {route}\n")
        out.append(_workload(broker, vid, f"{images}/databroker:dev", ["--net=host"], ["--port", port]))
        out.append(_workload(f"{vid}-simulator", vid, f"{images}/vehicle:dev", app_options,
                             ["vehicle.simulator.main"], depends_on=broker))
        out.append(_workload(f"{vid}-detector", vid, f"{images}/vehicle:dev", app_options,
                             ["vehicle.hazard_detector.main"], depends_on=broker))
    return "".join(out)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--out", type=Path, default=OUT, help=f"where to write (default {OUT.relative_to(ROOT)})")
    parser.add_argument("--images", default="localhost/sdv-fleet",
                        help="image prefix, e.g. a registry path on the cloud VM")
    args = parser.parse_args()

    fleet = json.loads(FLEET.read_text(encoding="utf-8"))
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(render(fleet, args.images), encoding="utf-8")
    print(f"Wrote {args.out} for {len(fleet['vehicles'])} vans: "
          + ", ".join(v["vehicle_id"] for v in fleet["vehicles"]))


if __name__ == "__main__":
    main()
